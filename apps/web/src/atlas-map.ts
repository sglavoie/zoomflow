import { classifyHref, indexBoards, resolveFilePath, type Diagram } from '@zoomflow/core';
import { quote } from './flow-model';

/** A link from one project file to another, by project path, with the `#/…` board fragment it opens or `''`. */
export type FileLink = { path: string; hash: string };
/** A project file and the files its links open; `failed` when it did not compile, so its links are unknown. */
export type AtlasFile = { path: string; links: FileLink[]; failed?: boolean };

const heading = '# Atlas map: generated by Zoomflow from the project files. Changes here are not saved.';
export const atlasMapName = 'Atlas map';
export const unlinkedLabel = 'Not linked from anywhere';

/** The links of every board of a compiled file to other files of its project, each once. */
export function fileLinks(diagram: Diagram, path: string): FileLink[] {
  const links = new Map<string, FileLink>();
  for (const board of indexBoards(diagram).values()) {
    for (const item of [...board.diagram.shapes, ...board.diagram.connections]) {
      const href = classifyHref(item.link ?? '');
      const target = href.kind === 'file' ? resolveFilePath(path, href.path) : undefined;
      if (href.kind !== 'file' || target === undefined || target === path) continue;
      const hash = href.hash === '#/' ? '' : href.hash;
      links.set(`${target}\n${hash}`, { path: target, hash });
    }
  }
  return [...links.values()];
}

/** The board a fragment opens, named like the link cues do: its last segment, decoded. */
function boardLabel(hash: string) {
  const segment = hash.split('/').filter(Boolean).at(-1) ?? '';
  try { return decodeURIComponent(segment); } catch { return segment; }
}

/** D2 source drawing each file as a shape that opens it and each file link as a connection, labelled with the board
 * it opens. Files that no other file links to, except `home`, sit in one container so they stand out. The map is
 * compiled as the project root's `index`, so its links are the project paths from there. */
export function atlasMapSource(files: AtlasFile[], home?: string): string {
  const sorted = [...files].sort((a, b) => a.path.localeCompare(b.path));
  const present = new Set(sorted.map((file) => file.path));
  const linked = new Set(sorted.flatMap((file) => file.links.filter((link) => present.has(link.path)).map((link) => link.path)));
  const unlinked = sorted.filter((file) => !linked.has(file.path) && file.path !== home);
  const ids = new Map(sorted.map((file, index) => [file.path, `${unlinked.includes(file) ? 'unlinked.' : ''}file_${index + 1}`]));
  const shape = (file: AtlasFile) => {
    const href = `./${file.path}`;
    const fields = [classifyHref(href).kind === 'file' ? `link: ${quote(href)}` : '',
      file.failed ? `tooltip: ${quote('This file did not compile, so its links are not shown.')}` : ''].filter(Boolean);
    const id = ids.get(file.path)!.replace(/^unlinked\./, '');
    return `${id}: ${quote(file.path.replace(/\.d2$/i, ''))}${fields.length ? ` {${fields.join('; ')}}` : ''}`;
  };
  const lines = [heading, 'direction: right', ''];
  lines.push(...sorted.filter((file) => !unlinked.includes(file)).map(shape));
  if (unlinked.length) lines.push('', `unlinked: ${quote(unlinkedLabel)} {`, ...unlinked.map((file) => `  ${shape(file)}`), '}');
  const connections = sorted.flatMap((file) => file.links.filter((link) => present.has(link.path)).map((link) =>
    `${ids.get(file.path)} -> ${ids.get(link.path)}${link.hash ? `: ${quote(boardLabel(link.hash))}` : ''}`));
  if (connections.length) lines.push('', ...connections);
  return `${lines.join('\n')}\n`;
}
